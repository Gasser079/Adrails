// Adrails discovery→tools compiler (build-time).
// Reads the Google Ads v25 discovery document and emits a trimmed, typed tool
// catalog for the cloud expert. GOLDEN RULE AT COMPILE TIME: only read-only
// methods become tools (GET + explicit read POSTs). Every mutating method is
// EXCLUDED — writes exit solely through the Action Ledger tools.
// Run: node apps/expert-agent/scripts/compile-discovery-tools.mjs
//   -> apps/expert-agent/src/discovery-tools.generated.ts
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const doc = JSON.parse(
  fs.readFileSync(path.join(here, "..", "..", "..", "packages", "ads-client", "discovery", "googleads-v25-schema.json"), "utf8"),
);

// Read-only POST actions (searches, generators, lookups). Everything else
// that mutates must travel the ledger path, never a direct tool.
const READ_POSTS = new Set([
  "generateKeywordIdeas", "generateKeywordHistoricalMetrics", "generateKeywordForecastMetrics",
  "search", "listAccessibleCustomers", "generateReachForecast", "generateAudienceCompositionInsights",
  "generateAudienceOverlapInsights", "searchAudienceInsightsAttributes", "listInsightsEligibleDates",
  "generateCreatorInsights", "generateTrendingInsights", "generateInsightsFinderReport",
  "suggestKeywordThemes", "suggestBrands", "suggestTravelAssets", "suggestSmartCampaignAd",
  "suggestSmartCampaignBudgetOptions", "generateAdGroupThemes", "generateTargetingSuggestionMetrics",
  "generateSuggestedTargetingInsights", "generateShareablePreviews", "generateBenchmarksMetrics",
  "listPlannableProducts", "listPlannableLocations", "listPlannableUserInterests", "listPlannableUserLists",
  "generateConversionRates", "listBenchmarksSources",
]);

const tools = [];
function walk(prefix, res) {
  for (const [name, m] of Object.entries(res.methods ?? {})) {
    const isGet = m.httpMethod === "GET";
    const leaf = name.split(".").pop();
    if (!isGet && !READ_POSTS.has(leaf) && !READ_POSTS.has(name)) continue;
    const id = (m.id ?? `googleads.${prefix}.${name}`).replace(/^googleads\./, "");
    const toolName = id.replace(/[^a-zA-Z0-9_.-]/g, "_").replace(/\./g, "_").slice(0, 64);
    const params = { type: "object", properties: {}, required: [] };
    for (const [k, v] of Object.entries(m.parameters ?? {})) {
      const prop = { type: v.type ?? "string", description: String(v.description ?? "").slice(0, 200) };
      if (v.enum) prop.enum = v.enum;
      params.properties[k] = prop;
      if (v.required) params.required.push(k);
    }
    // customerId is injected by the executor from tenant scope, never the model.
    delete params.properties.customerId;
    params.required = params.required.filter((k) => k !== "customerId");
    tools.push({
      name: toolName,
      description: `${String(m.description ?? "").slice(0, 280)} [Google Ads API v25, read-only]`,
      parameters: params,
      httpMethod: m.httpMethod,
      path: m.path,
      scopes: m.scopes ?? [],
    });
  }
  for (const [name, sub] of Object.entries(res.resources ?? {})) walk(prefix ? `${prefix}.${name}` : name, sub);
}
for (const [name, res] of Object.entries(doc.resources ?? {})) walk(name, res);

const out = `// GENERATED by scripts/compile-discovery-tools.mjs — do not edit.
// Source: googleads v25 discovery doc (${tools.length} read-only tools).
export interface DiscoveryToolDef {
  name: string;
  description: string;
  parameters: { type: "object"; properties: Record<string, unknown>; required: string[] };
  httpMethod: string;
  path: string;
  scopes: string[];
}
export const DISCOVERY_TOOLS: DiscoveryToolDef[] = ${JSON.stringify(tools, null, 2)};
export const DISCOVERY_VERSION = "v25";
`;
fs.writeFileSync(path.join(here, "..", "src", "discovery-tools.generated.ts"), out, "utf8");
console.log(`compiled ${tools.length} read-only tools (mutating methods excluded by design)`);
